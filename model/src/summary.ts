// Builds model/out/summary.md from the run results.
import type { RunResult } from './sim.ts';
import { ALIEN_KINDS, RES, type ResKey, type StorageVariant } from './types.ts';

export interface RunRecord {
  strategy: string;
  description: string;
  variant: StorageVariant;
  result: RunResult;
}

export interface SensitivityRow {
  label: string;
  outcomes: Record<string, string>;
}

export interface SummaryInput {
  mapName: string;
  seed: number;
  runs: RunRecord[];
  drainComparison: { strategy: string; variant: StorageVariant; perResource: RunResult; global: RunResult }[];
  sensitivity: { strategies: string[]; baseline: Record<string, string>; rows: SensitivityRow[] };
}

export const mmss = (t: number): string => `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;
const int = (x: number): string => Math.round(x).toLocaleString('en-GB');
const triple = (r: Record<ResKey, number>): string => RES.map((k) => int(r[k])).join(' / ');

export function outcomeCell(r: RunResult): string {
  if (r.outcome === 'won') return `won (${Math.round((100 * r.commanderHp) / r.commanderMaxHp)}% HP)`;
  if (r.outcome === 'lost') return `lost, wave ${r.waveReached} at ${mmss(r.endTime)}`;
  return `${r.outcome} at ${mmss(r.endTime)}`;
}

/** Minutes in which a resource slowed builds for at least `min` seconds, as ranges "3–9, 14". */
export function biteMinutes(perMinute: number[], min = 20): string {
  const mins = perMinute.map((s, i) => (s >= min ? i : -1)).filter((i) => i >= 0);
  if (!mins.length) return '—';
  const ranges: string[] = [];
  let start = mins[0];
  let prev = mins[0];
  for (const m of [...mins.slice(1), Infinity]) {
    if (m !== prev + 1) {
      ranges.push(start === prev ? `${start}` : `${start}–${prev}`);
      start = m;
    }
    prev = m;
  }
  return ranges.join(', ');
}

export function buildSummary(inp: SummaryInput): string {
  const L: string[] = [];
  const by = (s: string, v: StorageVariant) => inp.runs.find((r) => r.strategy === s && r.variant === v)!.result;
  const strategies = [...new Set(inp.runs.map((r) => r.strategy))];

  L.push(`# W12 economy and wave-pacing model — summary`, '');
  L.push(`${inp.mapName}, ${inp.runs[0].result.wavesTotal} waves, seed ${inp.seed}, 10 ticks per second. Generated by \`npm run model\`; do not edit by hand.`, '');
  L.push('Resource triples are mass / energy / rare. "Slowed" counts seconds in which at least one build or research item progressed below full speed because a resource ran short, attributed to the scarcest resource that tick. "Worst ratio" is the lowest share of a tick\'s requested draw the pool could cover.', '');

  L.push('## Outcomes', '');
  L.push('| Strategy | Storage | Result | Waves reached | Time of loss | Commander HP end (min) | Worst ratio (resource, time) | Slowed s (m / e / r) | Mean pool (m / e / r) | Wasted overflow (m / e / r) | Parts made / dry s |');
  L.push('|---|---|---|---|---|---|---|---|---|---|---|');
  for (const rr of inp.runs) {
    const r = rr.result;
    L.push(
      `| ${rr.strategy} | ${rr.variant} | ${outcomeCell(r)} | ${r.waveReached} / ${r.wavesTotal} | ${r.outcome === 'lost' ? mmss(r.endTime) : '—'} | ${int(r.commanderHp)} (${int(r.commanderMinHp)}) | ${Math.round(r.minEfficiency * 100)}% (${r.minEfficiencyResource || '—'}, ${mmss(r.minEfficiencyTime)}) | ${triple(r.slowedSeconds)} | ${triple(r.meanPool)} | ${triple(r.wasted)} | ${int(r.partsMade)} / ${int(r.heavyDrySeconds)} |`,
    );
  }
  L.push('');

  L.push('## Storage caps: uncapped against Forged Alliance-style caps', '');
  L.push('Capped: the commander holds 600 mass / 3,000 energy / 40 rare; each storage building adds 600 / 3,000 / 60; overflow above the cap is wasted. Strategies build storage only in the capped variant.', '');
  L.push('| Strategy | Uncapped | Capped | Earned, uncapped (m / e / r) | Earned, capped | Wasted, capped | Mass-slowed s, uncapped → capped |');
  L.push('|---|---|---|---|---|---|---|');
  for (const s of strategies) {
    const u = by(s, 'uncapped');
    const c = by(s, 'capped');
    L.push(`| ${s} | ${outcomeCell(u)} | ${outcomeCell(c)} | ${triple(u.earned)} | ${triple(c.earned)} | ${triple(c.wasted)} | ${int(u.slowedSeconds.mass)} → ${int(c.slowedSeconds.mass)} |`);
  }
  L.push('');

  L.push('## Where shortages bite', '');
  L.push('Game minutes in which a resource slowed builds for at least 20 s.', '');
  L.push('| Strategy | Storage | Mass | Energy | Rare |');
  L.push('|---|---|---|---|---|');
  for (const rr of inp.runs) {
    const r = rr.result;
    L.push(`| ${rr.strategy} | ${rr.variant} | ${biteMinutes(r.slowedByMinute.mass)} | ${biteMinutes(r.slowedByMinute.energy)} | ${biteMinutes(r.slowedByMinute.rare)} |`);
  }
  L.push('');

  L.push('## Breaches and losses', '');
  L.push('| Strategy | Storage | Reached base (' + ALIEN_KINDS.join(' / ') + ') | Commander damage by kind | Kills | Salvage from kills / reclaimed / decayed | Buildings lost |');
  L.push('|---|---|---|---|---|---|---|');
  for (const rr of inp.runs) {
    const r = rr.result;
    const lost = Object.entries(r.lost).map(([k, v]) => `${k} ${v}`).join(', ') || '—';
    L.push(
      `| ${rr.strategy} | ${rr.variant} | ${ALIEN_KINDS.map((k) => r.reachedBase[k]).join(' / ')} | ${ALIEN_KINDS.map((k) => int(r.commanderDamageBy[k])).join(' / ')} | ${r.kills} | ${int(r.salvageFromKills)} / ${int(r.reclaimed)} / ${int(r.decayed)} | ${lost} |`,
    );
  }
  L.push('');

  L.push('## Research completion', '');
  L.push('| Strategy | Storage | Research done (game minute) |');
  L.push('|---|---|---|');
  for (const rr of inp.runs) L.push(`| ${rr.strategy} | ${rr.variant} | ${rr.result.researchDone.map((x) => `${x.id} ${mmss(x.time)}`).join(', ') || '—'} |`);
  L.push('');

  L.push('## Drain rule: per-resource against one global factor', '');
  L.push('Per-resource (used for every result above): a build slows by the lowest supply ratio among the resources it draws. Global: the scarcest resource slows every build, including builds that do not use it.', '');
  L.push('| Strategy | Storage | Per-resource | Global | Slowed s per-resource (m / e / r) | Slowed s global |');
  L.push('|---|---|---|---|---|---|');
  for (const d of inp.drainComparison)
    L.push(`| ${d.strategy} | ${d.variant} | ${outcomeCell(d.perResource)} | ${outcomeCell(d.global)} | ${triple(d.perResource.slowedSeconds)} | ${triple(d.global.slowedSeconds)} |`);
  L.push('');

  L.push('## Sensitivity (uncapped)', '');
  L.push('Each row changes one number and reruns every strategy. A result that differs from the baseline row is in bold.', '');
  const ss = inp.sensitivity.strategies;
  L.push(`| Change | ${ss.join(' | ')} |`);
  L.push(`|---|${ss.map(() => '---').join('|')}|`);
  L.push(`| baseline | ${ss.map((s) => inp.sensitivity.baseline[s]).join(' | ')} |`);
  for (const row of inp.sensitivity.rows) {
    L.push(
      `| ${row.label} | ${ss
        .map((s) => {
          const base = inp.sensitivity.baseline[s].split(' ')[0];
          const v = row.outcomes[s];
          return v.split(' ')[0] !== base ? `**${v}**` : v;
        })
        .join(' | ')} |`,
    );
  }
  L.push('');

  L.push('## Strategies', '');
  for (const s of strategies) L.push(`- **${s}**: ${inp.runs.find((r) => r.strategy === s)!.description}`);
  L.push('');
  return L.join('\n');
}
